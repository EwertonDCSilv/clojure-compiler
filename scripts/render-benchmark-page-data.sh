#!/usr/bin/env bash
# Render the benchmark values consumed by docs/index.html from comparison CSVs.
set -euo pipefail
export LC_NUMERIC=C

if [[ "$#" -ne 4 ]]; then
  printf '%s\n' \
    "Uso: scripts/render-benchmark-page-data.sh CRACKING.csv CORMEN.csv EXERCISM.csv SAIDA.js" >&2
  exit 2
fi

cracking_csv="$1"
cormen_csv="$2"
exercism_csv="$3"
output="$4"

aggregate() {
  local csv="$1"
  awk -F, '
    NR == 1 {
      if ($1 != "benchmark" || $4 != "native_wall_time_s" ||
          $7 != "native_cpu_total_s" || $9 != "native_max_rss_kb" ||
          $12 != "clojure_wall_time_s" || $15 != "clojure_cpu_total_s" ||
          $17 != "clojure_max_rss_kb" || $23 != "status") {
        printf "schema de benchmark inesperado em %s\n", FILENAME > "/dev/stderr"
        exit 1
      }
      next
    }
    {
      if ($23 != "OK") {
        printf "benchmark %s tem status %s em %s\n", $1, $23, FILENAME > "/dev/stderr"
        exit 1
      }
      native_wall += $4
      native_cpu += $7
      clojure_wall += $12
      clojure_cpu += $15
      native_rss[++count] = $9
      clojure_rss[count] = $17
    }
    function sort(values, size, i, j, value) {
      for (i = 2; i <= size; i++) {
        value = values[i]
        j = i - 1
        while (j >= 1 && values[j] > value) {
          values[j + 1] = values[j]
          j--
        }
        values[j + 1] = value
      }
    }
    function median(values, size) {
      sort(values, size)
      if (size % 2 == 1)
        return values[(size + 1) / 2]
      return (values[size / 2] + values[size / 2 + 1]) / 2
    }
    END {
      if (count == 0)
        exit 1
      printf "%.2f %.2f %.2f %.2f %.1f %.1f\n", \
        native_wall, clojure_wall, native_cpu, clojure_cpu, \
        median(native_rss, count) / 1024, median(clojure_rss, count) / 1024
    }
  ' "$csv"
}

read -r cracking_native_wall cracking_clojure_wall \
  cracking_native_cpu cracking_clojure_cpu \
  cracking_native_memory cracking_clojure_memory < <(aggregate "$cracking_csv")
read -r cormen_native_wall cormen_clojure_wall \
  cormen_native_cpu cormen_clojure_cpu \
  cormen_native_memory cormen_clojure_memory < <(aggregate "$cormen_csv")
read -r exercism_native_wall exercism_clojure_wall \
  exercism_native_cpu exercism_clojure_cpu \
  exercism_native_memory exercism_clojure_memory < <(aggregate "$exercism_csv")

mkdir -p "$(dirname "$output")"
temporary="${output}.tmp"
trap 'rm -f "$temporary"' EXIT
{
  printf '%s\n' '// Generated by scripts/render-benchmark-page-data.sh. Do not edit.'
  printf '%s\n' 'window.benchmarkPageData = {'
  printf '  "cormen": {"wall": [%s, %s], "cpu": [%s, %s], "memory": [%s, %s]},\n' \
    "$cormen_native_wall" "$cormen_clojure_wall" \
    "$cormen_native_cpu" "$cormen_clojure_cpu" \
    "$cormen_native_memory" "$cormen_clojure_memory"
  printf '  "cracking": {"wall": [%s, %s], "cpu": [%s, %s], "memory": [%s, %s]},\n' \
    "$cracking_native_wall" "$cracking_clojure_wall" \
    "$cracking_native_cpu" "$cracking_clojure_cpu" \
    "$cracking_native_memory" "$cracking_clojure_memory"
  printf '  "exercism": {"wall": [%s, %s], "cpu": [%s, %s], "memory": [%s, %s]}\n' \
    "$exercism_native_wall" "$exercism_clojure_wall" \
    "$exercism_native_cpu" "$exercism_clojure_cpu" \
    "$exercism_native_memory" "$exercism_clojure_memory"
  printf '%s\n' '};'
} >"$temporary"
mv "$temporary" "$output"
